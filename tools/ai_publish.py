"""Publish advisory model findings through trusted, separate GitHub operations."""

import argparse
import json
from dataclasses import dataclass
from pathlib import Path

from pydantic import BaseModel, TypeAdapter

from tools.ai_audit_tickets import (
    TicketReceipt,
    fingerprint,
    propose_tickets,
    safe_text,
)
from tools.ai_contract import Analysis, valid_findings
from tools.ai_telemetry import mapping
from tools.github_api import github_api

PAGE_SIZE = 100
MARKER = "<!-- showcase-ai-review -->"


class RemoteUser(BaseModel):
    """The identity fields needed to recognize our own bot comment."""

    login: str


class RemoteComment(BaseModel):
    """The safe subset of GitHub issue-comment data."""

    id: int
    body: str
    user: RemoteUser


class RemoteIssue(BaseModel):
    """The fields used to maintain one weekly health issue."""

    number: int
    title: str


@dataclass(frozen=True)
class ReviewContext:
    """Trusted PR coordinates supplied by the workflow event."""

    repository: str
    number: int
    head_sha: str
    diff: str


def own_comment(context: ReviewContext) -> RemoteComment | None:
    """Find the existing marker across comment pages, ignoring human comments."""
    page = 1
    while True:
        endpoint = (
            f"repos/{context.repository}/issues/{context.number}/comments"
            f"?per_page={PAGE_SIZE}&page={page}"
        )
        comments = TypeAdapter(list[RemoteComment]).validate_python(
            github_api(endpoint)
        )
        for comment in comments:
            if comment.user.login == "github-actions[bot]" and comment.body.startswith(
                MARKER
            ):
                return comment
        if len(comments) < PAGE_SIZE:
            return None
        page += 1


def write_receipt(receipt: dict[str, object], path: Path | None) -> None:
    """Keep only publication join coordinates, never full API response bodies."""
    if path is None:
        return
    reduced = dict(receipt)
    for key in ("comment", "check", "issue"):
        if key in receipt:
            value = mapping(receipt[key])
            reduced[key] = {
                name: value[name]
                for name in ("id", "number", "html_url")
                if name in value
            }
    path.write_text(json.dumps(reduced), encoding="utf-8")


def post_review(
    context: ReviewContext, analysis: Analysis, *, receipt_path: Path | None = None
) -> dict[str, object]:
    """Update a sticky summary and emit neutral notice annotations, never reviews."""
    findings = valid_findings(analysis, context.diff)
    details = "\n\n".join(
        f"- `{finding.path}:{finding.line}`: {finding.body}" for finding in findings
    )
    body = (
        f"{MARKER}\n## AI coding review (advisory, non-blocking)\n\n"
        f"{analysis.summary}\n\n{details}\n\n"
        "Generated by MiMo 2.6 Flash through isolated OpenCode. "
        "This analysis cannot approve or block a merge."
    )
    existing = own_comment(context)
    if existing is None:
        comment = github_api(
            f"repos/{context.repository}/issues/{context.number}/comments",
            "POST",
            {"body": body},
        )
    else:
        comment = github_api(
            f"repos/{context.repository}/issues/comments/{existing.id}",
            "PATCH",
            {"body": body},
        )
    receipt: dict[str, object] = {
        "status": "partially_published",
        "mode": "review",
        "comment": comment,
        "findings_published": len(findings),
    }
    write_receipt(receipt, receipt_path)
    annotations = [
        {
            "path": finding.path,
            "start_line": finding.line,
            "end_line": finding.line,
            "annotation_level": "notice",
            "message": f"AI advisory (non-blocking): {finding.body}",
        }
        for finding in findings
    ]
    check = github_api(
        f"repos/{context.repository}/check-runs",
        "POST",
        {
            "name": "AI advisory",
            "head_sha": context.head_sha,
            "status": "completed",
            "conclusion": "neutral",
            "output": {
                "title": "MiMo 2.6 Flash coding review",
                "summary": analysis.summary,
                "annotations": annotations,
            },
        },
    )
    receipt.update(status="published", check=check)
    write_receipt(receipt, receipt_path)
    return receipt


def post_audit(
    repository: str, analysis: Analysis, *, receipt_path: Path | None = None
) -> dict[str, object]:
    """Create or update one issue without repeatedly notifying through comments."""
    title = "Weekly health report"
    issues = TypeAdapter(list[RemoteIssue]).validate_python(
        github_api(
            f"repos/{repository}/issues?state=open&labels=governance&per_page=100"
        )
    )
    existing = next((issue for issue in issues if issue.title == title), None)

    def checkpoint(tickets: list[TicketReceipt]) -> None:
        write_receipt(
            {
                "status": "partially_published",
                "mode": "audit",
                "tickets": [ticket.model_dump() for ticket in tickets],
            },
            receipt_path,
        )

    tickets = propose_tickets(repository, analysis.findings, checkpoint=checkpoint)
    links = {ticket.fingerprint: ticket for ticket in tickets}
    details: list[str] = []
    for finding in analysis.findings:
        ticket = links[fingerprint(repository, finding)]
        coordinate = (
            f"#{ticket.number}" if ticket.number else "deferred: five-ticket cap"
        )
        details.append(
            f"### {safe_text(finding.title)[:250]}\n\n"
            f"{finding.severity}: {coordinate} ({ticket.status})\n\n"
            f"Path: {safe_text(finding.path)[:350]}\n\n"
            f"Evidence excerpt: {safe_text(finding.evidence)[:600]}\n\n"
            f"Suggested fix excerpt: {safe_text(finding.suggested_fix)[:600]}"
        )
    body = {
        "title": title,
        "body": (
            "## AI coding audit (advisory)\n\n"
            + safe_text(analysis.summary)[:12000]
            + "\n\n"
            + "\n\n".join(details)
            + "\n\nGenerated by MiMo 2.6 Flash through isolated OpenCode. "
            "Verify findings before changing code."
        ),
        "labels": ["governance", "ai-generated"],
    }
    endpoint = f"repos/{repository}/issues"
    if existing is not None:
        issue = github_api(f"{endpoint}/{existing.number}", "PATCH", body)
    else:
        issue = github_api(endpoint, "POST", body)
    return {
        "status": "published",
        "mode": "audit",
        "issue": issue,
        "tickets": [ticket.model_dump() for ticket in tickets],
    }


def main() -> None:
    """Publish already-validated analysis from an artifact."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", choices=["review", "audit"], required=True)
    parser.add_argument("--repository", required=True)
    parser.add_argument("--analysis", type=Path, required=True)
    parser.add_argument("--number", type=int, default=0)
    parser.add_argument("--head-sha", default="")
    parser.add_argument("--diff", type=Path)
    parser.add_argument("--receipt", type=Path)
    args = parser.parse_args()
    analysis = Analysis.model_validate_json(args.analysis.read_text(encoding="utf-8"))
    if args.mode == "audit":
        receipt = post_audit(args.repository, analysis, receipt_path=args.receipt)
    else:
        diff = args.diff.read_text(encoding="utf-8") if args.diff else ""
        context = ReviewContext(args.repository, args.number, args.head_sha, diff)
        receipt = post_review(context, analysis, receipt_path=args.receipt)
    if args.receipt:
        write_receipt(receipt, args.receipt)


if __name__ == "__main__":
    main()
